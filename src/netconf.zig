pub const RaInfo = struct {
    slaac: bool = false,
    dhcpv6: bool = false,
};

pub const V6Mode = enum { slaac, dhcp };

/// RA A-bit (SLAAC) beats M-bit (DHCPv6); heuristics only run when the RA
/// carries neither flag -- hence the lazy function pointers.
pub fn chooseV6Mode(ra: RaInfo, slaac_signal: *const fn () bool, dhcp_signal: *const fn () bool) V6Mode {
    if (ra.slaac) return .slaac;
    if (ra.dhcpv6) return .dhcp;
    if (slaac_signal()) return .slaac;
    if (dhcp_signal()) return .dhcp;
    return .slaac;
}

/// Parse rdisc6 output for the A and M bits. "Stateful other conf." must
/// not be mistaken for address configuration.
pub fn parseRA(out: []const u8) RaInfo {
    var ra: RaInfo = .{};
    var lines = std.mem.splitScalar(u8, out, '\n');
    while (lines.next()) |line| {
        if (line.len > 256) continue;
        var low_buf: [256]u8 = undefined;
        for (line, 0..) |c, i| low_buf[i] = std.ascii.toLower(c);
        const low = low_buf[0..line.len];
        if (std.mem.indexOf(u8, low, "autonomous address conf") != null) {
            ra.slaac = std.mem.indexOf(u8, low, "yes") != null;
        } else if (std.mem.indexOf(u8, low, "stateful address conf") != null) {
            ra.dhcpv6 = std.mem.indexOf(u8, low, "yes") != null;
        }
    }
    return ra;
}

/// Parse `ip route get` output; both the `dev=` token style and the
/// `via GW dev IF` word style are accepted (second pass wins, like Go).
pub fn parseRouteGet(out: []const u8) struct { iface: []const u8, src: []const u8, gw: []const u8 } {
    var iface: []const u8 = "";
    var src: []const u8 = "";
    var gw: []const u8 = "";

    var pass1 = std.mem.tokenizeAny(u8, out, " \t\n\r");
    while (pass1.next()) |f| {
        if (std.mem.startsWith(u8, f, "dev=")) iface = f[4..] else if (std.mem.startsWith(u8, f, "src=")) src = f[4..] else if (std.mem.startsWith(u8, f, "via=")) gw = f[4..];
    }
    var pass2 = std.mem.tokenizeAny(u8, out, " \t\n\r");
    var prev: []const u8 = "";
    while (pass2.next()) |f| {
        if (std.mem.eql(u8, prev, "via")) gw = f else if (std.mem.eql(u8, prev, "dev")) iface = f else if (std.mem.eql(u8, prev, "src")) src = f;
        prev = f;
    }
    return .{ .iface = iface, .src = src, .gw = gw };
}

pub const ResolvParse = struct {
    dns4: []const []const u8,
    dns6: []const []const u8,
    other: []const []const u8,
};

/// Parse resolv.conf, dropping servers unusable on the target system.
/// `reachable` is injected so tests can fake VPN routes.
pub fn parseResolv(
    arena: std.mem.Allocator,
    data: []const u8,
    reachable: *const fn ([]const u8) bool,
) !ResolvParse {
    var dns4: std.ArrayList([]const u8) = .empty;
    var dns6: std.ArrayList([]const u8) = .empty;
    var other: std.ArrayList([]const u8) = .empty;

    var lines = std.mem.splitScalar(u8, data, '\n');
    while (lines.next()) |raw| {
        const line = std.mem.trim(u8, raw, " \t\r");
        if (line.len == 0 or line[0] == '#' or line[0] == ';') continue;
        var it = std.mem.tokenizeAny(u8, line, " \t");
        const kw = it.next() orelse continue;
        if (std.mem.eql(u8, kw, "nameserver")) {
            const s = it.next() orelse continue;
            if (!usableDNS(s)) continue;
            const host = if (std.mem.indexOfScalar(u8, s, '%')) |i| s[0..i] else s;
            if (!reachable(host)) continue;
            const ip = std.Io.net.IpAddress.parse(host, 0) catch continue;
            switch (ip) {
                .ip4 => try appendUnique(&dns4, arena, s),
                .ip6 => try appendUnique(&dns6, arena, s),
            }
        } else if (std.mem.eql(u8, kw, "search") or
            std.mem.eql(u8, kw, "domain") or
            std.mem.eql(u8, kw, "options"))
        {
            try other.append(arena, line);
        }
    }
    return .{
        .dns4 = try dns4.toOwnedSlice(arena),
        .dns6 = try dns6.toOwnedSlice(arena),
        .other = try other.toOwnedSlice(arena),
    };
}

/// Whether a nameserver may be written into the target resolv.conf.
/// Loopback stubs, link-local and CGNAT (Tailscale MagicDNS) are local-only;
/// private IPv4 is fine -- IDC networks use it for DNS all the time.
pub fn usableDNS(s: []const u8) bool {
    const host = if (std.mem.indexOfScalar(u8, s, '%')) |i| s[0..i] else s;
    const ip = std.Io.net.IpAddress.parse(host, 0) catch return false;
    switch (ip) {
        .ip4 => |a| {
            const b = a.bytes;
            if (b[0] == 127) return false;
            if (b[0] == 169 and b[1] == 254) return false;
            if (b[0] == 224 and b[1] == 0 and b[2] == 0) return false;
            if (b[0] == 100 and b[1] >= 64 and b[1] <= 127) return false;
            return true;
        },
        .ip6 => |a| {
            const b = a.bytes;
            if (isLoopback6(b)) return false;
            if (b[0] == 0xFE and (b[1] & 0xC0) == 0x80) return false;
            if (b[0] == 0xFF and b[1] == 0x02) return false;
            if (b[0] & 0xFE == 0xFC) return false; // fc00::/7 ULA
            return true;
        },
    }
}

fn isLoopback6(b: [16]u8) bool {
    for (0..15) |i| {
        if (b[i] != 0) return false;
    }
    return b[15] == 1;
}

/// Parse `ip -o [-f family] addr show` output into global addresses.
/// The first `addr/prefix` token per line wins; flags are read from the
/// whole line, mirroring Go listAddrs.
pub fn parseAddrOutput(
    arena: std.mem.Allocator,
    family: enum { inet, inet6 },
    out: []const u8,
) ![]const Address {
    var list: std.ArrayList(Address) = .empty;
    var lines = std.mem.splitScalar(u8, out, '\n');
    while (lines.next()) |line| {
        var it = std.mem.tokenizeAny(u8, line, " \t");
        while (it.next()) |f| {
            const slash = std.mem.indexOfScalar(u8, f, '/') orelse continue;
            const host = f[0..slash];
            const pstr = f[slash + 1 ..];
            const ip = std.Io.net.IpAddress.parse(host, 0) catch continue;
            if (isLoopbackAny(ip) or isLinkLocalAny(ip)) continue;
            const is4 = switch (ip) {
                .ip4 => true,
                .ip6 => false,
            };
            if (family == .inet and !is4) continue;
            if (family == .inet6 and is4) continue;
            const p = std.fmt.parseInt(u8, pstr, 10) catch continue;
            if (p < 1 or p > 128 or (family == .inet and p > 32)) continue;
            try list.append(arena, .{
                .ip = host,
                .prefix = p,
                .dynamic = lineHasField(line, "dynamic"),
                .temporary = lineHasField(line, "temporary"),
                .mngtmp = lineHasField(line, "mngtmpaddr"),
                .secondary = lineHasField(line, "secondary"),
            });
            break;
        }
    }
    return list.toOwnedSlice(arena);
}

fn isLoopbackAny(ip: std.Io.net.IpAddress) bool {
    return switch (ip) {
        .ip4 => |a| a.bytes[0] == 127,
        .ip6 => |a| isLoopback6(a.bytes),
    };
}

fn isLinkLocalAny(ip: std.Io.net.IpAddress) bool {
    return switch (ip) {
        .ip4 => |a| a.bytes[0] == 169 and a.bytes[1] == 254,
        .ip6 => |a| a.bytes[0] == 0xFE and (a.bytes[1] & 0xC0) == 0x80,
    };
}

fn lineHasField(line: []const u8, field: []const u8) bool {
    var it = std.mem.tokenizeAny(u8, line, " \t");
    while (it.next()) |f| {
        if (std.mem.eql(u8, f, field)) return true;
    }
    return false;
}

/// Primary v4 address: src match first, then first non-secondary.
/// Callers guarantee `addrs` is non-empty.
pub fn chooseV4(addrs: []const Address, src: []const u8) Address {
    for (addrs) |a| {
        if (std.mem.eql(u8, a.ip, src)) return a;
    }
    for (addrs) |a| {
        if (!a.secondary) return a;
    }
    return addrs[0];
}

/// Primary v6 address: src match first, then first non-temporary.
pub fn chooseV6(addrs: []const Address, src: []const u8) Address {
    for (addrs) |a| {
        if (std.mem.eql(u8, a.ip, src) and !a.temporary) return a;
    }
    for (addrs) |a| {
        if (!a.temporary) return a;
    }
    return addrs[0];
}

