//! Live network detection, address helpers and ifupdown/resolv.conf rendering.
const std = @import("std");

pub const Address = struct {
    ip: []const u8 = "",
    prefix: u8 = 0,
    dynamic: bool = false,
    temporary: bool = false,
    mngtmp: bool = false,
    secondary: bool = false,

    pub fn cidr(self: Address, arena: std.mem.Allocator) ![]const u8 {
        return std.fmt.allocPrint(arena, "{s}/{d}", .{ self.ip, self.prefix });
    }
};

pub const IPv6 = struct {
    iface: []const u8 = "",
    mac: []const u8 = "",
    address: []const u8 = "",
    prefix: u8 = 0,
    gateway: []const u8 = "",
    extra: []const []const u8 = &.{},
    slaac: bool = false,
    dhcpv6: bool = false,
    static: bool = false,
    disable_ra: bool = false,
    disable_autoconf: bool = false,

    pub fn present(self: IPv6) bool {
        return self.iface.len > 0 and self.address.len > 0;
    }
};

pub const Net = struct {
    iface: []const u8 = "",
    mac: []const u8 = "",
    ip: []const u8 = "",
    prefix: u8 = 0,
    netmask: []const u8 = "",
    gateway: []const u8 = "",
    extra4: []const []const u8 = &.{},
    dhcp: bool = false,
    static: bool = false,
    has_v4: bool = false,
    dns4: []const []const u8 = &.{},
    dns6: []const []const u8 = &.{},
    resolv_other: []const []const u8 = &.{},
    v6: IPv6 = .{},

    pub fn present(self: Net) bool {
        return self.has_v4 or self.v6.present();
    }

    /// IPv4/IPv6 DNS merged without duplicates; allocated from `arena`.
    pub fn dns(self: Net, arena: std.mem.Allocator) ![]const []const u8 {
        var out: std.ArrayList([]const u8) = .empty;
        for (self.dns4) |d| try appendUnique(&out, arena, d);
        for (self.dns6) |d| try appendUnique(&out, arena, d);
        return out.toOwnedSlice(arena);
    }
};

pub const RenderOptions = struct {
    release: i32 = 0,
    dns4: []const []const u8 = &.{},
    dns6: []const []const u8 = &.{},
    write_dns4: bool = false,
    write_dns6: bool = false,
};

