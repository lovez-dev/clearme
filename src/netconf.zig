fn parseV4Bytes(s: []const u8) ![4]u8 {
    const ip = std.Io.net.IpAddress.parse(s, 0) catch return error.NotIp;
    return switch (ip) {
        .ip4 => |a| a.bytes,
        else => error.NotIp,
    };
}

/// Accept only ordinary Linux NIC names before splicing them into scripts.
pub fn validIface(name: []const u8) bool {
    if (name.len == 0 or name.len > 32) return false;
    for (name) |c| {
        const ok = (c >= 'a' and c <= 'z') or (c >= 'A' and c <= 'Z') or (c >= '0' and c <= '9') or
            c == '-' or c == '_' or c == '.' or c == ':';
        if (!ok) return false;
    }
    return true;
}

fn appendUnique(list: *std.ArrayList([]const u8), arena: std.mem.Allocator, s: []const u8) !void {
    if (s.len == 0) return;
    for (list.items) |x| {
        if (std.mem.eql(u8, x, s)) return;
    }
    try list.append(arena, s);
}

pub fn parseIPv6(s: []const u8) ?struct { addr: []const u8, prefix: u8 } {
    if (std.mem.indexOfScalar(u8, s, '/')) |i| {
        const addr = s[0..i];
        const pfx_s = s[i + 1 ..];
        if (pfx_s.len == 0 or pfx_s.len > 3) return null;
        for (pfx_s) |c| {
            if (c < '0' or c > '9') return null;
        }
        const pfx = std.fmt.parseInt(u8, pfx_s, 10) catch return null;
        if (pfx > 128) return null;
        _ = parseV6Bytes(addr) catch return null;
        return .{ .addr = addr, .prefix = pfx };
    }
    _ = parseV6Bytes(s) catch return null;
    return .{ .addr = s, .prefix = 64 };
}

