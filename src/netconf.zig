/// Generate the complete /etc/network/interfaces for the target system.
pub fn renderInterfaces(arena: std.mem.Allocator, n: Net, o: RenderOptions) ![]const u8 {
    var out: std.ArrayList(u8) = .empty;
    try out.print(arena, "# Generated by clearme; preserving the pre-reinstall network configuration\n", .{});
    try out.print(arena, "source /etc/network/interfaces.d/*\n\n", .{});
    try out.print(arena, "auto lo\niface lo inet loopback\n", .{});

    var main: []const u8 = "";
    if (validIface(n.iface) and !std.mem.eql(u8, n.iface, "lo")) main = n.iface;
    var v6 = n.v6;
    if (!v6.present()) v6 = .{};

    if (main.len > 0) {
        try out.print(arena, "\n", .{});
        if (n.mac.len > 0) try out.print(arena, "# mac {s}\n", .{n.mac});
        try out.print(arena, "auto {s}\n", .{main});
        if (n.has_v4 and (n.ip.len > 0 or n.dhcp)) {
            if (n.dhcp) {
                try out.print(arena, "iface {s} inet dhcp\n", .{main});
            } else {
                try out.print(arena, "iface {s} inet static\n", .{main});
                try out.print(arena, "    address {s}\n", .{try v4Address(arena, n)});
                if (n.gateway.len > 0) {
                    if (v4GatewayOffSubnet(n.gateway, n.ip, n.prefix)) {
                        try out.print(arena, "    post-up ip -4 route replace {s}/32 dev {s}\n", .{ n.gateway, main });
                        try out.print(arena, "    post-up ip -4 route replace default via {s} dev {s} onlink\n", .{ n.gateway, main });
                        try out.print(arena, "    pre-down ip -4 route del default via {s} dev {s} || true\n", .{ n.gateway, main });
                        try out.print(arena, "    pre-down ip -4 route del {s}/32 dev {s} || true\n", .{ n.gateway, main });
                    } else try out.print(arena, "    gateway {s}\n", .{n.gateway});
                }
            }
            if (o.write_dns4) {
                for (o.dns4) |d| try out.print(arena, "    dns-nameservers {s}\n", .{d});
            }
        }
        if (v6.present() and std.mem.eql(u8, v6.iface, main)) {
            try renderV6(&out, arena, v6, o);
        }
    }

    // The IPv6 default route may live on a different NIC.
    if (v6.present() and !std.mem.eql(u8, v6.iface, main) and validIface(v6.iface)) {
        try out.print(arena, "\n# IPv6 is configured on a different interface\n", .{});
        try out.print(arena, "auto {s}\n", .{v6.iface});
        try renderV6(&out, arena, v6, o);
    }

    return out.toOwnedSlice(arena);
}

fn renderV6(out: *std.ArrayList(u8), arena: std.mem.Allocator, v: IPv6, o: RenderOptions) !void {
    if (v.slaac) {
        try out.print(arena, "iface {s} inet6 auto\n", .{v.iface});
    } else if (v.dhcpv6) {
        // Debian 13's dhcpcd-base loses IPv4 when inet+inet6 both say dhcp.
        const mode: []const u8 = if (o.release >= 13) "auto" else "dhcp";
        try out.print(arena, "iface {s} inet6 {s}\n", .{ v.iface, mode });
    } else if (v.static) {
        try out.print(arena, "iface {s} inet6 static\n", .{v.iface});
        try out.print(arena, "    address {s}/{d}\n", .{ v.address, v.prefix });
        if (v.gateway.len > 0) {
            if (v6GatewayOffSubnet(v.gateway, v.address, v.prefix)) {
                // ifupdown inet6 static has no onlink gateway; add routes first.
                try out.print(arena, "    post-up ip -6 route add {s} dev {s}\n", .{ v.gateway, v.iface });
                try out.print(arena, "    post-up ip -6 route add default via {s} dev {s}\n", .{ v.gateway, v.iface });
            } else {
                try out.print(arena, "    gateway {s}\n", .{v.gateway});
            }
        }
        for (v.extra) |extra| {
            try out.print(arena, "    post-up ip -6 addr add {s} dev {s}\n", .{ extra, v.iface });
        }
    }
    if (o.write_dns6) {
        for (o.dns6) |d| try out.print(arena, "    dns-nameserver {s}\n", .{d});
    }
    if (v.disable_ra) {
        try out.print(arena, "    accept_ra 0\n", .{});
    } else if (v.slaac or v.dhcpv6) {
        // Kernel optimization enables forwarding. Keep router advertisements
        // working on dynamic IPv6 interfaces even when forwarding is enabled.
        try out.print(arena, "    accept_ra 2\n", .{});
    }
    if (v.disable_autoconf) try out.print(arena, "    autoconf 0\n", .{});
}

/// Generate the target /etc/resolv.conf: servers first, then kept options.
pub fn renderResolvConf(arena: std.mem.Allocator, servers: []const []const u8, other: []const []const u8) ![]const u8 {
    var out: std.ArrayList(u8) = .empty;
    try out.print(arena, "# Written by clearme\n", .{});
    for (servers) |s| try out.print(arena, "nameserver {s}\n", .{s});
    for (other) |raw| {
        const line = std.mem.trim(u8, raw, " \t\r\n");
        if (line.len == 0 or line[0] == '#') continue;
        try out.print(arena, "{s}\n", .{line});
    }
    return out.toOwnedSlice(arena);
}

pub const DnsPair = struct { v4: []const []const u8, v6: []const []const u8 };

/// Public fallback resolvers; china selects domestic servers.
pub fn fallbackDNS(china: bool) DnsPair {
    if (china) return .{
        .v4 = &.{ "223.5.5.5", "119.29.29.29" },
        .v6 = &.{ "2400:3200::1", "2402:4e00::" },
    };
    return .{
        .v4 = &.{ "1.1.1.1", "8.8.8.8" },
        .v6 = &.{ "2606:4700:4700::1111", "2001:4860:4860::8888" },
    };
}

