/// IO handles threaded through detect; set once by detectOn (single-threaded
/// CLI) so injected callbacks like reachableDNS can reach them.
var g_io: ?std.Io = null;
var g_arena: ?std.mem.Allocator = null;

pub const CmdOutput = struct {
    ok: bool,
    stdout: []const u8,
};

/// Run argv, capture trimmed stdout. A non-zero exit keeps stdout but sets
/// ok=false, matching Go's system.Output + err check pattern.
pub fn runCmd(io: std.Io, arena: std.mem.Allocator, argv: []const []const u8) CmdOutput {
    var child = std.process.spawn(io, .{
        .argv = argv,
        .stdin = .ignore,
        .stdout = .pipe,
        .stderr = .ignore,
    }) catch return .{ .ok = false, .stdout = "" };
    defer child.kill(io);

    var reader = child.stdout.?.readerStreaming(io, &.{});
    const raw = reader.interface.allocRemaining(arena, .limited(4 << 20)) catch
        return .{ .ok = false, .stdout = "" };
    const term = child.wait(io) catch return .{ .ok = false, .stdout = "" };
    const ok = switch (term) {
        .exited => |code| code == 0,
        else => false,
    };
    return .{ .ok = ok, .stdout = std.mem.trim(u8, raw, " \t\r\n") };
}

fn readFile(io: std.Io, arena: std.mem.Allocator, path: []const u8) ?[]const u8 {
    return std.Io.Dir.cwd().readFileAlloc(io, path, arena, .limited(4 << 20)) catch null;
}

/// Detect the current network configuration. `iface` may be "auto"/"" to
/// follow the default route, or a concrete NIC name.
pub fn detectOn(io: std.Io, arena: std.mem.Allocator, iface: []const u8) !Net {
    g_io = io;
    g_arena = arena;

    var n: Net = .{};
    if (validIface(iface) and !std.mem.eql(u8, iface, "auto") and !std.mem.eql(u8, iface, "lo")) {
        n.iface = iface;
        n.gateway = defaultGateway(io, arena, iface, "4");
        try detectV4AddrsOn(io, arena, &n, iface, "");
        n.v6 = detectV6On(io, arena, iface);
    } else {
        try detectByRoute(io, arena, &n);
    }
    if (n.iface.len == 0 and n.v6.iface.len > 0) n.iface = n.v6.iface;
    if (validIface(n.iface) and !std.mem.eql(u8, n.iface, "lo")) {
        n.mac = readMAC(io, arena, n.iface);
    }
    n.static = n.has_v4 and !n.dhcp;

    const resolv = readResolv(io, arena);
    n.dns4 = resolv.dns4;
    n.dns6 = resolv.dns6;
    n.resolv_other = resolv.other;

    if (!n.present()) return error.NoNetwork;
    return n;
}

fn detectByRoute(io: std.Io, arena: std.mem.Allocator, n: *Net) !void {
    const r = runCmd(io, arena, &.{ "ip", "route", "get", "1.1.1.1" });
    if (r.ok) {
        const parsed = parseRouteGet(r.stdout);
        if (validIface(parsed.iface) and !std.mem.eql(u8, parsed.iface, "lo")) {
            n.iface = parsed.iface;
            n.gateway = parsed.gw;
            try detectV4AddrsOn(io, arena, n, parsed.iface, parsed.src);
        }
    }
    n.v6 = try detectV6(io, arena);
}

fn detectV4AddrsOn(io: std.Io, arena: std.mem.Allocator, n: *Net, iface: []const u8, src: []const u8) !void {
    const r = runCmd(io, arena, &.{ "ip", "-o", "-f", "inet", "addr", "show", "dev", iface, "scope", "global" });
    if (!r.ok) return;
    const addrs = try parseAddrOutput(arena, .inet, r.stdout);
    if (addrs.len == 0) return;
    const prim = chooseV4(addrs, src);
    n.ip = prim.ip;
    n.prefix = prim.prefix;
    n.netmask = prefixToMaskAlloc(arena, prim.prefix) orelse "";
    n.dhcp = prim.dynamic;
    n.has_v4 = true;
    var extra: std.ArrayList([]const u8) = .empty;
    for (addrs) |a| {
        if (!sameAddr(a, prim) and !a.dynamic) {
            try extra.append(arena, try std.fmt.allocPrint(arena, "{s}/{d}", .{ a.ip, a.prefix }));
        }
    }
    n.extra4 = try extra.toOwnedSlice(arena);
}

fn detectV6(io: std.Io, arena: std.mem.Allocator) !IPv6 {
    var iface: []const u8 = "";
    var src: []const u8 = "";
    var gw: []const u8 = "";
    const r = runCmd(io, arena, &.{ "ip", "-6", "route", "get", "2001:4860:4860::8888" });
    if (r.ok) {
        const parsed = parseRouteGet(r.stdout);
        iface = parsed.iface;
        src = parsed.src;
        gw = parsed.gw;
    }
    if (!validIface(iface) or std.mem.eql(u8, iface, "lo")) {
        iface = firstV6Iface(io, arena);
        src = "";
        gw = "";
    }
    if (iface.len == 0) return .{};
    return buildV6(io, arena, iface, src, gw);
}

fn detectV6On(io: std.Io, arena: std.mem.Allocator, iface: []const u8) IPv6 {
    if (!validIface(iface) or std.mem.eql(u8, iface, "lo")) return .{};
    const gw = defaultGateway(io, arena, iface, "6");
    var src: []const u8 = "";
    const r = runCmd(io, arena, &.{ "ip", "-6", "route", "get", "2001:4860:4860::8888", "dev", iface });
    if (r.ok) src = parseRouteGet(r.stdout).src;
    return buildV6(io, arena, iface, src, gw);
}

fn buildV6(io: std.Io, arena: std.mem.Allocator, iface: []const u8, src: []const u8, gw: []const u8) IPv6 {
    const r = runCmd(io, arena, &.{ "ip", "-o", "-f", "inet6", "addr", "show", "dev", iface, "scope", "global" });
    if (!r.ok) return .{};
    const addrs = parseAddrOutput(arena, .inet6, r.stdout) catch return .{};
    if (addrs.len == 0) return .{};
    const prim = chooseV6(addrs, src);

    var v: IPv6 = .{
        .iface = iface,
        .mac = readMAC(io, arena, iface),
        .address = prim.ip,
        .prefix = prim.prefix,
        .gateway = gw,
    };

    const ra = probeRA(io, arena, iface);
    if (!prim.dynamic) {
        // No dynamic marker: treat as static and disable RA/autoconf so a
        // reboot does not mint another address or default route.
        v.static = true;
        v.disable_ra = true;
        v.disable_autoconf = true;
        var extra: std.ArrayList([]const u8) = .empty;
        for (addrs) |a| {
            if (!sameAddr(a, prim) and !a.temporary and !a.dynamic and !a.mngtmp) {
                const cidr = std.fmt.allocPrint(arena, "{s}/{d}", .{ a.ip, a.prefix }) catch continue;
                tryAppend(&extra, arena, cidr);
            }
        }
        v.extra = extra.toOwnedSlice(arena) catch &.{};
        return v;
    }

    // Equivalent to chooseV6Mode's lazy short-circuit; function pointers
    // cannot capture addrs/iface here.
    if (ra.slaac) {
        v.slaac = true;
    } else if (ra.dhcpv6) {
        v.dhcpv6 = true;
    } else if (v6SLAACSignal(io, arena, addrs)) {
        v.slaac = true;
    } else if (v6DHCP(io, arena, iface, prim.ip)) {
        v.dhcpv6 = true;
    } else {
        v.slaac = true;
    }
    return v;
}

fn tryAppend(list: *std.ArrayList([]const u8), arena: std.mem.Allocator, s: []const u8) void {
    list.append(arena, s) catch {};
}

fn sameAddr(a: Address, b: Address) bool {
    return a.prefix == b.prefix and std.mem.eql(u8, a.ip, b.ip);
}

fn prefixToMaskAlloc(arena: std.mem.Allocator, prefix: u8) ?[]const u8 {
    if (prefix == 0 or prefix > 32) return null;
    return std.fmt.allocPrint(arena, "{d}.{d}.{d}.{d}", .{
        maskByte(prefix, 0), maskByte(prefix, 1), maskByte(prefix, 2), maskByte(prefix, 3),
    }) catch null;
}

/// Privacy addresses or a default route with proto ra imply SLAAC.
fn v6SLAACSignal(io: std.Io, arena: std.mem.Allocator, addrs: []const Address) bool {
    for (addrs) |a| {
        if (a.temporary or a.mngtmp) return true;
    }
    const r = runCmd(io, arena, &.{ "ip", "-6", "route", "show", "default" });
    return r.ok and std.mem.indexOf(u8, r.stdout, "proto ra") != null;
}

/// proto dhcp on the default route, or an address found in a lease file.
fn v6DHCP(io: std.Io, arena: std.mem.Allocator, iface: []const u8, ip: []const u8) bool {
    const r = runCmd(io, arena, &.{ "ip", "-6", "route", "show", "default", "dev", iface });
    if (r.ok and std.mem.indexOf(u8, r.stdout, "proto dhcp") != null) return true;
    return leaseHas(io, arena, ip);
}

fn leaseHas(io: std.Io, arena: std.mem.Allocator, ip: []const u8) bool {
    const patterns = [_][]const u8{
        "/var/lib/dhcp/dhclient*.leases",
        "/var/lib/dhcpcd/*.lease",
        "/var/lib/dhcpcd/*.lease.*",
        "/var/lib/isc-dhcp/dhclient*.leases",
        "/run/systemd/netif/leases/*",
        "/var/lib/NetworkManager/*.lease",
    };
    for (patterns) |pat| {
        const files = globFiles(io, arena, pat) catch continue;
        for (files) |path| {
            const data = readFile(io, arena, path) orelse continue;
            if (std.mem.indexOf(u8, data, ip) != null) return true;
        }
    }
    return false;
}

fn globFiles(io: std.Io, arena: std.mem.Allocator, pattern: []const u8) ![]const []const u8 {
    const slash = std.mem.lastIndexOfScalar(u8, pattern, '/') orelse return error.NoSlash;
    const dir_path = pattern[0..slash];
    const name_pat = pattern[slash + 1 ..];
    var dir = std.Io.Dir.cwd().openDir(io, dir_path, .{ .iterate = true }) catch return &.{};
    defer dir.close(io);
    var list: std.ArrayList([]const u8) = .empty;
    var it = dir.iterate();
    while (it.next(io) catch null) |entry| {
        if (!globMatch(name_pat, entry.name)) continue;
        const p = try std.fmt.allocPrint(arena, "{s}/{s}", .{ dir_path, entry.name });
        try list.append(arena, p);
    }
    return list.toOwnedSlice(arena);
}

/// Single-star glob like Go's filepath.Glob for the patterns above.
fn globMatch(pat: []const u8, name: []const u8) bool {
    var p_i: usize = 0;
    var n_i: usize = 0;
    var star_p: usize = std.math.maxInt(usize);
    var star_n: usize = 0;
    while (n_i < name.len) {
        if (p_i < pat.len and pat[p_i] == name[n_i]) {
            p_i += 1;
            n_i += 1;
        } else if (p_i < pat.len and pat[p_i] == '*') {
            star_p = p_i;
            star_n = n_i;
            p_i += 1;
        } else if (star_p != std.math.maxInt(usize)) {
            p_i = star_p + 1;
            star_n += 1;
            n_i = star_n;
        } else return false;
    }
    while (p_i < pat.len and pat[p_i] == '*') p_i += 1;
    return p_i == pat.len;
}

fn probeRA(io: std.Io, arena: std.mem.Allocator, iface: []const u8) RaInfo {
    // rdisc6 -1 sends one probe; no extra timeout needed beyond its own.
    const r = runCmd(io, arena, &.{ "rdisc6", "-1", iface });
    if (!r.ok and r.stdout.len == 0) return .{};
    return parseRA(r.stdout);
}

fn firstV6Iface(io: std.Io, arena: std.mem.Allocator) []const u8 {
    const r = runCmd(io, arena, &.{ "ip", "-6", "-o", "addr", "show", "scope", "global" });
    if (!r.ok) return "";
    var lines = std.mem.splitScalar(u8, r.stdout, '\n');
    while (lines.next()) |line| {
        var it = std.mem.tokenizeAny(u8, line, " \t");
        _ = it.next() orelse continue; // index
        const raw_name = it.next() orelse continue;
        const name = if (std.mem.endsWith(u8, raw_name, ":")) raw_name[0 .. raw_name.len - 1] else raw_name;
        if (validIface(name) and !std.mem.eql(u8, name, "lo")) return name;
    }
    return "";
}

fn defaultGateway(io: std.Io, arena: std.mem.Allocator, iface: []const u8, family: []const u8) []const u8 {
    const flag: []const u8 = if (std.mem.eql(u8, family, "4")) "-4" else "-6";
    const r = runCmd(io, arena, &.{ "ip", flag, "route", "show", "default", "dev", iface });
    if (!r.ok) return "";
    var lines = std.mem.splitScalar(u8, r.stdout, '\n');
    while (lines.next()) |line| {
        var it = std.mem.tokenizeAny(u8, line, " \t");
        var prev: []const u8 = "";
        while (it.next()) |f| {
            if (std.mem.eql(u8, prev, "via")) return f;
            prev = f;
        }
    }
    return "";
}

fn readMAC(io: std.Io, arena: std.mem.Allocator, iface: []const u8) []const u8 {
    const sys_path = std.fmt.allocPrint(arena, "/sys/class/net/{s}/address", .{iface}) catch return "";
    if (readFile(io, arena, sys_path)) |data| {
        return toLowerAlloc(arena, std.mem.trim(u8, data, " \t\r\n")) catch "";
    }
    const r = runCmd(io, arena, &.{ "ip", "link", "show", "dev", iface });
    if (!r.ok) return "";
    var lines = std.mem.splitScalar(u8, r.stdout, '\n');
    while (lines.next()) |line| {
        var it = std.mem.tokenizeAny(u8, line, " \t");
        var prev: []const u8 = "";
        while (it.next()) |f| {
            if (std.mem.eql(u8, prev, "link/ether")) {
                return toLowerAlloc(arena, f) catch "";
            }
            prev = f;
        }
    }
    return "";
}

fn toLowerAlloc(arena: std.mem.Allocator, s: []const u8) ![]const u8 {
    const out = try arena.alloc(u8, s.len);
    for (s, 0..) |c, i| out[i] = std.ascii.toLower(c);
    return out;
}

fn readResolv(io: std.Io, arena: std.mem.Allocator) ResolvParse {
    const data = readFile(io, arena, "/etc/resolv.conf") orelse
        return .{ .dns4 = &.{}, .dns6 = &.{}, .other = &.{} };
    return parseResolv(arena, data, reachableDNS) catch
        .{ .dns4 = &.{}, .dns6 = &.{}, .other = &.{} };
}

const tunnel_prefixes = [_][]const u8{
    "tun", "tap", "wg", "tailscale", "utun", "ppp", "nordlynx", "zt", "ipsec", "nebula",
};

/// Keep a nameserver only when its route leaves via a physical NIC.
fn reachableDNS(host: []const u8) bool {
    const io = g_io orelse return true;
    const arena = g_arena orelse return true;
    const r = runCmd(io, arena, &.{ "ip", "route", "get", host });
    if (!r.ok) return true;
    const parsed = parseRouteGet(r.stdout);
    if (parsed.iface.len == 0) return true;
    for (tunnel_prefixes) |p| {
        if (std.mem.startsWith(u8, parsed.iface, p)) return false;
    }
    return true;
}

