fn v4Address(arena: std.mem.Allocator, n: Net) ![]const u8 {
    var p = n.prefix;
    if (p == 0 or p > 32) p = maskToPrefix(n.netmask);
    if (p == 0) return n.ip;
    return std.fmt.allocPrint(arena, "{s}/{d}", .{ n.ip, p });
}

/// True when a non-link-local gateway sits outside the address's subnet and
/// needs onlink post-up routes.
pub fn v6GatewayOffSubnet(gateway: []const u8, address: []const u8, prefix: u8) bool {
    const g = parseV6Bytes(gateway) catch return false;
    const a = parseV6Bytes(address) catch return false;
    if (isLinkLocal(g)) return false;
    if (prefix == 0 or prefix > 128) return false;
    for (0..16) |i| {
        const m = maskByte(prefix, i);
        if ((a[i] & m) != (g[i] & m)) return true;
    }
    return false;
}

fn parseV6Bytes(s: []const u8) ![16]u8 {
    const ip = std.Io.net.IpAddress.parse(s, 0) catch return error.NotIp;
    return switch (ip) {
        .ip6 => |a| a.bytes,
        else => error.NotIp,
    };
}

fn isLinkLocal(b: [16]u8) bool {
    return b[0] == 0xFE and (b[1] & 0xC0) == 0x80;
}

/// Mask byte for `prefix` bits at byte index `idx` (32- or 128-bit space).
fn maskByte(prefix: u8, idx: usize) u8 {
    const start: u16 = @as(u16, @intCast(idx)) * 8;
    const p: u16 = prefix;
    if (p <= start) return 0x00;
    const left: u16 = p - start;
    if (left >= 8) return 0xFF;
    const shift: u3 = @intCast(8 - left);
    return @as(u8, 0xFF) << shift;
}

/// Dotted-quad for a CIDR prefix; null for 0 or >32 (Go returns "").
pub fn prefixToMask(buf: []u8, prefix: u8) ?[]const u8 {
    if (prefix == 0 or prefix > 32) return null;
    return std.fmt.bufPrint(buf, "{d}.{d}.{d}.{d}", .{
        maskByte(prefix, 0), maskByte(prefix, 1), maskByte(prefix, 2), maskByte(prefix, 3),
    }) catch unreachable;
}

/// CIDR prefix for a dotted-quad mask; 0 for invalid or non-contiguous.
pub fn maskToPrefix(mask: []const u8) u8 {
    const ip = std.Io.net.IpAddress.parse(mask, 0) catch return 0;
    const ip4 = switch (ip) {
        .ip4 => |a| a,
        else => return 0,
    };
    var ones: u8 = 0;
    var seen_zero = false;
    for (ip4.bytes) |byte| {
        var bit: u8 = 0x80;
        while (bit != 0) : (bit >>= 1) {
            if (byte & bit != 0) {
                if (seen_zero) return 0;
                ones += 1;
            } else seen_zero = true;
        }
    }
    return ones;
}

pub fn v4GatewayOffSubnet(gateway: []const u8, address: []const u8, prefix: u8) bool {
    if (prefix == 0 or prefix > 32) return false;
    const g = parseV4Bytes(gateway) catch return false;
    const a = parseV4Bytes(address) catch return false;
    for (0..4) |i| {
        const m = maskByte(prefix, i);
        if ((a[i] & m) != (g[i] & m)) return true;
    }
    return false;
}

