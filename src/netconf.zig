var test_slaac_ret: bool = false;
var test_dhcp_ret: bool = false;
var test_slaac_calls: usize = 0;
var test_dhcp_calls: usize = 0;
fn testSlaacSignal() bool {
    test_slaac_calls += 1;
    return test_slaac_ret;
