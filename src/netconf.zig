test "parseRA reads A and M bits" {
    const real =
        \\Hop limit                 :           64 (      0x40)
        \\Stateful address conf.    :           No
        \\Stateful other conf.      :          Yes
        \\ Prefix                   : 2001:db8::/64
        \\  Autonomous address conf.:          Yes
    ;
    const Case = struct { name: []const u8, out: []const u8, want: RaInfo };
    const cases = [_]Case{
        .{ .name = "both bits", .out = "Stateful address configuration: yes\nAutonomous address configuration: yes\n", .want = .{ .slaac = true, .dhcpv6 = true } },
        .{ .name = "m only", .out = "Stateful address configuration: yes\nAutonomous address configuration: no\n", .want = .{ .dhcpv6 = true } },
        .{ .name = "a only", .out = "Stateful address configuration: no\nAutonomous address configuration: yes\n", .want = .{ .slaac = true } },
        .{ .name = "real output", .out = real, .want = .{ .slaac = true } },
        .{ .name = "empty", .out = "", .want = .{} },
    };
    for (cases) |c| {
        try std.testing.expectEqual(c.want, parseRA(c.out));
    }
}

test "chooseV6Mode priority and lazy signals" {
    const Case = struct {
        ra: RaInfo,
        slaac: bool,
        dhcp: bool,
        want: V6Mode,
    };
    const cases = [_]Case{
        .{ .ra = .{ .slaac = true, .dhcpv6 = true }, .slaac = true, .dhcp = true, .want = .slaac },
        .{ .ra = .{ .dhcpv6 = true }, .slaac = true, .dhcp = false, .want = .dhcp },
        .{ .ra = .{}, .slaac = true, .dhcp = true, .want = .slaac },
        .{ .ra = .{}, .slaac = false, .dhcp = true, .want = .dhcp },
        .{ .ra = .{}, .slaac = false, .dhcp = false, .want = .slaac },
    };
    for (cases) |c| {
        test_slaac_ret = c.slaac;
        test_dhcp_ret = c.dhcp;
        test_slaac_calls = 0;
        test_dhcp_calls = 0;
        const got = chooseV6Mode(c.ra, testSlaacSignal, testDhcpSignal);
        try std.testing.expectEqual(c.want, got);
        if (c.ra.slaac or c.ra.dhcpv6) {
            try std.testing.expectEqual(@as(usize, 0), test_slaac_calls + test_dhcp_calls);
        }
    }
}

test "parseResolv drops local-only and tunnel DNS" {
    var a = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer a.deinit();
    const data =
        \\# comment
        \\nameserver 127.0.0.53
        \\nameserver 100.100.100.100
        \\nameserver fd7a:115c:a1e0::53
        \\nameserver fe80::1%eth0
        \\nameserver 192.168.1.1
        \\nameserver 2606:4700:4700::1111
        \\search example.com
    ;
    const r = try parseResolv(a.allocator(), data, alwaysReachable);
    try std.testing.expectEqual(@as(usize, 1), r.dns4.len);
    try std.testing.expectEqualStrings("192.168.1.1", r.dns4[0]);
    try std.testing.expectEqual(@as(usize, 1), r.dns6.len);
    try std.testing.expectEqualStrings("2606:4700:4700::1111", r.dns6[0]);
    try std.testing.expectEqual(@as(usize, 1), r.other.len);
    try std.testing.expectEqualStrings("search example.com", r.other[0]);
}

var test_tunnel_host: []const u8 = "";
fn tunnelReachable(host: []const u8) bool {
    return !std.mem.eql(u8, host, test_tunnel_host);
}
fn alwaysReachable(_: []const u8) bool {
    return true;
}

